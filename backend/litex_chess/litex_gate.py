class Gate(Protocol):
    def validate_move(self, position: Position, move: Move) -> tuple[CandidateTransition, GateReceipt]: ...
    def validate_position(self, position: Position) -> GateReceipt: ...
    def health(self) -> dict[str, Any]: ...
